    public function run(): void
    {
        $postojece = KalendarStavka::query()->get();

        foreach (self::stavke() as $stavka) {
            if ($postojece->contains(fn (KalendarStavka $postojeca) => self::jeVecTu($postojeca, $stavka))) {
                continue;
            }

            unset($stavka['kljuc']);
            KalendarStavka::query()->create([...$stavka, 'status' => StatusObjave::Objavljeno]);
        }
    }

